# 9. TASK 2 – SIMILARITY MEASURES
# ============================================================

def inner_product_similarity(document_vector, query_vector):
    """Sum(document_weight * query_weight)."""
    common_terms = set(document_vector) & set(query_vector)

    return sum(
        document_vector[term] * query_vector[term]
        for term in common_terms
    )


def cosine_similarity(document_vector, query_vector):
    """Cosine similarity between the document and query vectors."""
    common_terms = set(document_vector) & set(query_vector)

    dot_product = sum(
        document_vector[term] * query_vector[term]
        for term in common_terms
    )

    document_norm = sqrt(
        sum(weight ** 2 for weight in document_vector.values())
    )
    query_norm = sqrt(
        sum(weight ** 2 for weight in query_vector.values())
    )

    if document_norm == 0 or query_norm == 0:
        return 0.0

    return dot_product / (document_norm * query_norm)


def jaccard_similarity(document_vector, query_vector):
    """
    Weighted Jaccard similarity:
    sum(min(document_weight, query_weight)) /
    sum(max(document_weight, query_weight)).

    Query weights are binary (0 or 1), as required by LAB2.
    """
    all_terms = set(document_vector) | set(query_vector)

    if not all_terms:
        return 0.0

    numerator = sum(
        min(document_vector.get(term, 0.0),
            query_vector.get(term, 0.0))
        for term in all_terms
    )

    denominator = sum(
        max(document_vector.get(term, 0.0),
            query_vector.get(term, 0.0))
        for term in all_terms
    )

    if denominator == 0:
        return 0.0

    return numerator / denominator


def rank_documents(query_vector, document_vectors, similarity_function):
    results = []

    for doc_id, document_vector in document_vectors.items():
        score = similarity_function(document_vector, query_vector)
        results.append((doc_id, score))

    return sorted(results, key=lambda item: (-item[1], item[0]))


