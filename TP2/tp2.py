# 4. TASK 1 – BOOLEAN QUERY PARSER
# ============================================================

BOOLEAN_QUERY = "(query AND reformulation) OR (Language AND model)"

# Recognize parentheses, operators, and query terms.
BOOLEAN_TOKEN_PATTERN = re.compile(
    r"\(|\)|\bAND\b|\bOR\b|[A-Za-z0-9_]+",
    flags=re.IGNORECASE
)


def prepare_boolean_tokens(query):
    """Preprocess query terms while preserving AND, OR, and parentheses."""
    raw_tokens = BOOLEAN_TOKEN_PATTERN.findall(query)
    prepared = []

    for token in raw_tokens:
        upper = token.upper()

        if token in ("(", ")"):
            prepared.append(token)
        elif upper in ("AND", "OR"):
            prepared.append(upper)
        else:
            terms = preprocess(token)
            prepared.extend(terms)

    return prepared


class BooleanParser:
    """
    Recursive-descent parser.
    AND has higher precedence than OR.
    Parentheses have the highest precedence.
    """

    def __init__(self, tokens):
        self.tokens = tokens
        self.position = 0

    def current(self):
        if self.position < len(self.tokens):
            return self.tokens[self.position]
        return None

    def consume(self, expected=None):
        token = self.current()

        if token is None:
            raise ValueError("Unexpected end of Boolean query.")

        if expected is not None and token != expected:
            raise ValueError(
                f"Expected {expected}, but found {token}."
            )

        self.position += 1
        return token

    def parse(self):
        tree = self.parse_or()

        if self.current() is not None:
            raise ValueError(
                f"Unexpected token in Boolean query: {self.current()}"
            )

        return tree

    def parse_or(self):
        node = self.parse_and()

        while self.current() == "OR":
            self.consume("OR")
            right = self.parse_and()
            node = ("OR", node, right)

        return node

    def parse_and(self):
        node = self.parse_primary()

        while self.current() == "AND":
            self.consume("AND")
            right = self.parse_primary()
            node = ("AND", node, right)

        return node

    def parse_primary(self):
        token = self.current()

        if token == "(":
            self.consume("(")
            node = self.parse_or()
            self.consume(")")
            return node

        if token is None or token in ("AND", "OR", ")"):
            raise ValueError(f"Unexpected token: {token}")

        self.consume()
        return ("TERM", token)


def build_boolean_tree(query):
    tokens = prepare_boolean_tokens(query)
    return BooleanParser(tokens).parse()


