# 5. TASK 1 – CLASSIC BOOLEAN MODEL
# ============================================================

def evaluate_classic(node, document_terms):
    """Return True or False for a document."""
    operation = node[0]

    if operation == "TERM":
        return node[1] in document_terms

    left = evaluate_classic(node[1], document_terms)
    right = evaluate_classic(node[2], document_terms)

    if operation == "AND":
        return left and right

    if operation == "OR":
        return left or right

    raise ValueError(f"Unknown Boolean operation: {operation}")


def run_classic_boolean(tree, document_vectors):
    results = []

    for doc_id, vector in document_vectors.items():
        matched = evaluate_classic(tree, set(vector.keys()))

        if matched:
            results.append(doc_id)

    return results


