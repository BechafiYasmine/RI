# 6. TASK 1 – FUZZY BOOLEAN MODEL
# ============================================================

def term_relevance(term, document_vector):
    """
    Fuzzy membership of a term in a document.

    The TF-IDF weight from TP1 is used as the term's relevance degree.
    A missing term has relevance 0.
    """
    return document_vector.get(term, 0.0)


def evaluate_fuzzy(node, document_vector):
    """Use min for AND and max for OR."""
    operation = node[0]

    if operation == "TERM":
        return term_relevance(node[1], document_vector)

    left = evaluate_fuzzy(node[1], document_vector)
    right = evaluate_fuzzy(node[2], document_vector)

    if operation == "AND":
        return min(left, right)

    if operation == "OR":
        return max(left, right)

    raise ValueError(f"Unknown Boolean operation: {operation}")


def run_fuzzy_boolean(tree, document_vectors):
    results = []

    for doc_id, vector in document_vectors.items():
        score = evaluate_fuzzy(tree, vector)
        results.append((doc_id, score))

    return sorted(results, key=lambda item: (-item[1], item[0]))


