# 3. LOAD DOCUMENT-TERM FILES GENERATED BY TP1
# ============================================================

def find_index_directory():
    """Find the expected TP1 output folder, with a few useful fallbacks."""
    if INDEX_DIR.exists() and any(INDEX_DIR.glob("D*.txt")):
        return INDEX_DIR

    possible_dirs = [
        INDEX_DIR,
        BASE_DIR.parent / "TP1" / "results" / "split_porter",
        BASE_DIR / "results" / "regex_porter",
        BASE_DIR / "regex_porter",
        BASE_DIR / "results" / "split_porter",
    ]

    for directory in possible_dirs:
        if directory.exists() and all(
            (directory / f"{doc_id}.txt").exists()
            for doc_id in DOCUMENT_IDS
        ):
            return directory

    raise FileNotFoundError(
        "Could not find the TP1 Document-Term files.\n"
        "Expected D1.txt ... D6.txt inside:\n"
        f"  {INDEX_DIR}\n\n"
        "Run tp1.py first, or change INDEX_DIR at the top of tp2.py "
        "to the folder containing the six document-term files."
    )


def load_document_vectors():
    """
    Read the six Document-Term files.
    Each line: document_id term frequency weight
    """
    directory = find_index_directory()
    document_vectors = {doc_id: {} for doc_id in DOCUMENT_IDS}
    document_frequencies = {doc_id: {} for doc_id in DOCUMENT_IDS}

    for doc_id in DOCUMENT_IDS:
        file_path = directory / f"{doc_id}.txt"

        with open(file_path, "r", encoding="utf-8") as file:
            for line_number, line in enumerate(file, start=1):
                parts = line.strip().split()

                if not parts:
                    continue

                if len(parts) != 4:
                    raise ValueError(
                        f"Invalid line {line_number} in {file_path}:\n{line}"
                    )

                file_doc_id, term, frequency, weight = parts

                if file_doc_id != doc_id:
                    raise ValueError(
                        f"Expected {doc_id}, found {file_doc_id} "
                        f"in {file_path}, line {line_number}."
                    )

                document_frequencies[doc_id][term] = int(frequency)
                document_vectors[doc_id][term] = float(weight)

    print(f"Loaded Document-Term files from: {directory}")
    return document_vectors, document_frequencies


