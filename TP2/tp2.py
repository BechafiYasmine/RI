def print_ranked_results(results, score_name="Score"):
    if not results:
        print("No matching documents.")
        return

    print(f"{'Rank':<8}{'Document':<15}{score_name}")
    print("-" * 38)

    for rank, (doc_id, score) in enumerate(results, start=1):
        print(f"{rank:<8}{doc_id:<15}{score:.6f}")


