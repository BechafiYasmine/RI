# 7. TASK 1 – EXTENDED BOOLEAN MODEL (P-NORM)
# ============================================================

def pnorm_and(scores, p=P_VALUE):
    """
    Extended Boolean AND:
    1 - [average((1 - score_i)^p)]^(1/p)
    """
    if not scores:
        return 0.0

    value = sum((1.0 - score) ** p for score in scores) / len(scores)
    return 1.0 - value ** (1.0 / p)


def pnorm_or(scores, p=P_VALUE):
    """
    Extended Boolean OR:
    [average(score_i^p)]^(1/p)
    """
    if not scores:
        return 0.0

    value = sum(score ** p for score in scores) / len(scores)
    return value ** (1.0 / p)


def evaluate_extended(node, document_vector):
    operation = node[0]

    if operation == "TERM":
        return term_relevance(node[1], document_vector)

    left = evaluate_extended(node[1], document_vector)
    right = evaluate_extended(node[2], document_vector)

    if operation == "AND":
        return pnorm_and([left, right])

    if operation == "OR":
        return pnorm_or([left, right])

    raise ValueError(f"Unknown Boolean operation: {operation}")


def run_extended_boolean(tree, document_vectors):
    results = []

    for doc_id, vector in document_vectors.items():
        score = evaluate_extended(tree, vector)
        results.append((doc_id, score))

    return sorted(results, key=lambda item: (-item[1], item[0]))


